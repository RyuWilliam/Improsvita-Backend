-- =====================================================================
-- Improsvita :: migración del modelo suppliers -> contacts + contact_roles
--
-- Ejecutar UNA VEZ sobre la base de datos legacy ANTES de desplegar el
-- backend con el modelo de contactos. No se ejecuta automáticamente.
-- Probar primero sobre una copia.
--
-- Soporta dos estados de partida:
--   1) Tabla legacy suppliers (supplier_id, name, phone, email, ...).
--   2) Migración intermedia previa: suppliers(contact_id), clients(contact_id),
--      employees(contact_id) y contacts ya existente.
--
-- Resultado final:
--   contacts(contact_id, name, phone, email, created_date, last_updated, active)
--   contact_roles(contact_id, role) con PK (contact_id, role)
--   seeds_suppliers.supplier_id -> contacts.contact_id
--   seed_movement.supplier_id   -> contacts.contact_id
--   Sin tablas suppliers, clients ni employees.
-- =====================================================================

BEGIN;

DO $$
DECLARE
    suppliers_exists boolean;
    has_legacy_supplier_id boolean;
    has_role_contact_id boolean;
    has_supplier_ids boolean := false;
    max_contact_id integer;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = current_schema() AND table_name = 'suppliers'
    ) INTO suppliers_exists;

    -- 1. Tabla base de contactos
    CREATE TABLE IF NOT EXISTS contacts (
        contact_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name         VARCHAR(255) NOT NULL,
        phone        VARCHAR(255) NOT NULL,
        email        VARCHAR(255) NOT NULL UNIQUE,
        created_date TIMESTAMP,
        last_updated TIMESTAMP,
        active       BOOLEAN NOT NULL DEFAULT TRUE
    );

    IF suppliers_exists THEN
        SELECT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'suppliers' AND column_name = 'supplier_id'
        ) INTO has_legacy_supplier_id;

        SELECT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'suppliers' AND column_name = 'contact_id'
        ) INTO has_role_contact_id;

        IF has_legacy_supplier_id THEN
            -- 2a. Copiar proveedores legacy conservando sus IDs
            EXECUTE $sql$
                INSERT INTO contacts (contact_id, name, phone, email, created_date, last_updated, active)
                SELECT supplier_id, name, phone, email, created_date, last_updated, COALESCE(active, TRUE)
                FROM suppliers
                ON CONFLICT DO NOTHING
            $sql$;

            CREATE TEMP TABLE tmp_supplier_contacts ON COMMIT DROP AS
                SELECT supplier_id AS contact_id FROM suppliers;
            has_supplier_ids := true;

        ELSIF has_role_contact_id THEN
            -- 2b. La migración intermedia ya movió los datos a contacts
            CREATE TEMP TABLE tmp_supplier_contacts ON COMMIT DROP AS
                SELECT contact_id FROM suppliers
                WHERE contact_id IS NOT NULL;
            has_supplier_ids := true;
        END IF;
    END IF;

    -- 3. Tabla de roles
    CREATE TABLE IF NOT EXISTS contact_roles (
        contact_id INTEGER NOT NULL,
        role       VARCHAR(255) NOT NULL,
        CONSTRAINT pk_contact_roles PRIMARY KEY (contact_id, role),
        CONSTRAINT fk_contact_roles_contact
            FOREIGN KEY (contact_id) REFERENCES contacts (contact_id)
            ON DELETE CASCADE
    );

    CREATE INDEX IF NOT EXISTS idx_contact_roles_role
        ON contact_roles (role);

    -- 4. Todos los proveedores conservan el rol SUPPLIER
    IF has_supplier_ids THEN
        INSERT INTO contact_roles (contact_id, role)
        SELECT DISTINCT tc.contact_id, 'SUPPLIER'
        FROM tmp_supplier_contacts tc
        JOIN contacts c ON c.contact_id = tc.contact_id
        ON CONFLICT DO NOTHING;
    END IF;

    -- 5. Eliminar tablas del modelo anterior junto con sus FKs
    DROP TABLE IF EXISTS clients CASCADE;
    DROP TABLE IF EXISTS employees CASCADE;
    DROP TABLE IF EXISTS suppliers CASCADE;

    -- 6. Reapuntar las FKs de semillas/proveedores a contacts
    IF to_regclass(current_schema() || '.seeds_suppliers') IS NOT NULL THEN
        ALTER TABLE seeds_suppliers
            DROP CONSTRAINT IF EXISTS fk_seeds_suppliers_supplier;
        ALTER TABLE seeds_suppliers
            ADD CONSTRAINT fk_seeds_suppliers_supplier
            FOREIGN KEY (supplier_id) REFERENCES contacts (contact_id);
    END IF;

    IF to_regclass(current_schema() || '.seed_movement') IS NOT NULL THEN
        ALTER TABLE seed_movement
            DROP CONSTRAINT IF EXISTS fk_seed_movement_supplier;
        ALTER TABLE seed_movement
            ADD CONSTRAINT fk_seed_movement_supplier
            FOREIGN KEY (supplier_id) REFERENCES contacts (contact_id);
    END IF;

    -- 7. Ajustar la secuencia de contacts al máximo ID conservado
    max_contact_id := (SELECT MAX(contact_id) FROM contacts);
    IF max_contact_id IS NOT NULL AND pg_get_serial_sequence('contacts', 'contact_id') IS NOT NULL THEN
        PERFORM setval(pg_get_serial_sequence('contacts', 'contact_id'), max_contact_id);
    END IF;
END $$;

COMMIT;
