-- =====================================================================
-- Improsvita :: nueva tabla sales (ventas de plántulas)
--
-- Ejecutar UNA VEZ sobre la base de datos ANTES de desplegar el backend
-- con SaleEntity. No se ejecuta automáticamente. Probar sobre una copia.
--
-- En dev no hace falta: spring.jpa.hibernate.ddl-auto=create-drop crea
-- la tabla desde la entidad en cada arranque.
--
-- Modelo:
--   * Una venta siempre apunta a la siembra de donde sale el stock
--     (sowing_id NOT NULL).
--   * reservation_id es NULL en ventas directas y apunta a la reserva
--     cuando la venta es la entrega de esa reserva.
--   * contact_id es el comprador y debe tener el rol CLIENT (se valida
--     en la capa de servicio, no en la base).
--   * total = quantity * unit_price (lo calcula el servidor).
--   * Una reserva genera como máximo una venta (índice único parcial).
--
-- Resultado final:
--   tabla sales
--   índices idx_sales_contact, idx_sales_sowing, idx_sales_date,
--           uq_sales_reservation
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS sales (
    sale_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id     INTEGER NOT NULL,
    sowing_id      INTEGER NOT NULL,
    reservation_id INTEGER,
    sale_date      DATE NOT NULL,
    quantity       INTEGER NOT NULL,
    unit_price     NUMERIC(12, 2) NOT NULL,
    total          NUMERIC(12, 2) NOT NULL,
    sale_type      VARCHAR(20) NOT NULL,
    notes          TEXT,
    created_date   TIMESTAMP,
    last_updated   TIMESTAMP,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_sales_quantity   CHECK (quantity > 0),
    CONSTRAINT ck_sales_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sales_total      CHECK (total >= 0),
    CONSTRAINT ck_sales_type       CHECK (sale_type IN ('DIRECT', 'RESERVATION'))
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_sales_contact'
    ) THEN
        ALTER TABLE sales
            ADD CONSTRAINT fk_sales_contact
            FOREIGN KEY (contact_id) REFERENCES contacts (contact_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_sales_sowing'
    ) THEN
        ALTER TABLE sales
            ADD CONSTRAINT fk_sales_sowing
            FOREIGN KEY (sowing_id) REFERENCES sowings (sowing_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_sales_reservation'
    ) THEN
        ALTER TABLE sales
            ADD CONSTRAINT fk_sales_reservation
            FOREIGN KEY (reservation_id) REFERENCES reservations (reservation_id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_sales_contact ON sales (contact_id);
CREATE INDEX IF NOT EXISTS idx_sales_sowing  ON sales (sowing_id);
CREATE INDEX IF NOT EXISTS idx_sales_date    ON sales (sale_date);

-- Una reserva se factura como máximo una vez.
CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_reservation
    ON sales (reservation_id) WHERE reservation_id IS NOT NULL;

COMMIT;
