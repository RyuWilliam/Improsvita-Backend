-- =====================================================================
-- Improsvita :: migración clients -> contacts + contact_roles (CLIENT)
--
-- Ejecutar UNA VEZ después de contacts-migration.sql y ANTES de
-- desplegar el backend sin ClientEntity. Probar sobre una copia.
--
-- Resultado final:
--   contacts con todos los clientes y el rol CLIENT
--   reservations.contact_id -> contacts.contact_id
--   Sin tabla clients.
-- =====================================================================
BEGIN;

DO $$
DECLARE
    clients_exists boolean;
    reservations_exists boolean;
    has_client_id boolean;
    has_contact_id boolean;
    new_contact_id integer;
    r RECORD;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = current_schema() AND table_name = 'clients'
    ) INTO clients_exists;

    IF NOT clients_exists THEN
        RAISE NOTICE 'No existe la tabla clients; nada que migrar';
        RETURN;
    END IF;

    CREATE TABLE IF NOT EXISTS contacts (
        contact_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name         VARCHAR(255) NOT NULL,
        phone        VARCHAR(255) NOT NULL,
        email        VARCHAR(255) NOT NULL UNIQUE,
        created_date TIMESTAMP,
        last_updated TIMESTAMP,
        active       BOOLEAN NOT NULL DEFAULT TRUE
    );

    CREATE TABLE IF NOT EXISTS contact_roles (
        contact_id INTEGER NOT NULL,
        role       VARCHAR(255) NOT NULL,
        CONSTRAINT pk_contact_roles PRIMARY KEY (contact_id, role),
        CONSTRAINT fk_contact_roles_contact
            FOREIGN KEY (contact_id) REFERENCES contacts (contact_id)
            ON DELETE CASCADE
    );

    CREATE TEMP TABLE tmp_client_contact_map (
        old_client_id INTEGER PRIMARY KEY,
        new_contact_id INTEGER NOT NULL
    ) ON COMMIT DROP;

    FOR r IN SELECT * FROM clients ORDER BY client_id LOOP
        new_contact_id := NULL;

        SELECT contact_id INTO new_contact_id
        FROM contacts
        WHERE email = r.email
        LIMIT 1;

        IF new_contact_id IS NULL THEN
            INSERT INTO contacts (name, phone, email, created_date, last_updated, active)
            VALUES (r.name, r.phone, r.email, r.created_date, r.last_updated, COALESCE(r.active, TRUE))
            RETURNING contact_id INTO new_contact_id;
        END IF;

        INSERT INTO tmp_client_contact_map (old_client_id, new_contact_id)
        VALUES (r.client_id, new_contact_id);

        INSERT INTO contact_roles (contact_id, role)
        VALUES (new_contact_id, 'CLIENT')
        ON CONFLICT DO NOTHING;
    END LOOP;

    SELECT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = current_schema() AND table_name = 'reservations'
    ) INTO reservations_exists;

    IF reservations_exists THEN
        SELECT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'reservations' AND column_name = 'client_id'
        ) INTO has_client_id;

        SELECT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = 'reservations' AND column_name = 'contact_id'
        ) INTO has_contact_id;

        IF has_client_id AND NOT has_contact_id THEN
            ALTER TABLE reservations ADD COLUMN contact_id INTEGER;
        END IF;

        IF has_client_id THEN
            UPDATE reservations r
               SET contact_id = m.new_contact_id
              FROM tmp_client_contact_map m
             WHERE m.old_client_id = r.client_id;
            ALTER TABLE reservations DROP COLUMN client_id;
        END IF;

        IF has_client_id OR has_contact_id THEN
            ALTER TABLE reservations ALTER COLUMN contact_id SET NOT NULL;

            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint WHERE conname = 'fk_reservations_contact'
            ) THEN
                ALTER TABLE reservations
                    ADD CONSTRAINT fk_reservations_contact
                    FOREIGN KEY (contact_id) REFERENCES contacts (contact_id);
            END IF;

            CREATE INDEX IF NOT EXISTS idx_reservations_contact
                ON reservations (contact_id);
        END IF;
    END IF;

    DROP TABLE clients;
END $$;

COMMIT;
